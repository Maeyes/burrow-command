export function unlocksAtWarrenLevel(level){
 const rows=[];
 if(level===5)rows.push('กองทัพสูงสุด 9 ตัว','จ้างได้คลาสละ 2 ตัว','โรงตีเหล็กและโรงผลิตอัปได้ถึง Lv3');
 if(level===7)rows.push('กองทัพสูงสุด 11 ตัว');
 if(level===9)rows.push('กองทัพสูงสุด 14 ตัว');
 if(level===10)rows.push('โรงตีเหล็กและโรงผลิตอัปได้ถึง Lv5','Skill Core ชุดที่ 1 + Mod 2 ช่อง','Movement Skill และ Weapon Mastery Lv10');
 if(level===15)rows.push('กองทัพสูงสุด 21 ตัว','ยกเลิกเพดานจำนวนต่อคลาส','โรงตีเหล็กและโรงผลิตอัปได้ถึง Lv8','รถยิงเวทย์ 2 คัน');
 if(level===20)rows.push('โรงตีเหล็กและโรงผลิตอัปได้ถึง Lv10','รถยิงเวทย์สูงสุด 4 คัน','Skill Core ชุดที่ 2 + Mod 2 ช่อง','Weapon Mastery Lv20');
 if(level===25)rows.push('รถยิงเวทย์สูงสุด 6 คัน');
 if(level===30)rows.push('Skill Core ชุดที่ 3 + Mod 2 ช่อง','Weapon Mastery Lv30');
 return rows;
}

